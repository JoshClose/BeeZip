//! `cargo xtask codegen`: the files generated from the command registry. CI regenerates them
//! and fails on any diff.
//!
//! - `apps/desktop/src/gen/commands.ts` (docs/M0.md §4): the ts-rs declarations of every
//!   input and output type and of the shared engine types, with a typed `CommandMap`.
//! - `crates/beezip-menu/src/gen_exts.rs` (docs/M4.md §3.2): the extensions `formats.list`
//!   reports, so the Explorer menu knows archives without depending on beezip-core.

use std::{
    path::{Path, PathBuf},
    sync::Arc,
};

use anyhow::{Context, bail};
use beezip_commands::{
    CmdError, CommandInfo, Engine, JobEvent, JobInfo, NonInteractive, PromptReply, TsDecls,
    collect_ts, commands::FormatsListOutput, discard_events, registry,
};
use ts_rs::Config;

/// Relative to the workspace root.
pub const OUTPUT: &str = "apps/desktop/src/gen/commands.ts";
pub const EXTS_OUTPUT: &str = "crates/beezip-menu/src/gen_exts.rs";

const HEADER: &str = "\
// @generated by `cargo xtask codegen` from the beezip-commands registry. Do not edit.
// CI fails if this file is out of date; regenerate it after changing a command's types.
";

pub(crate) fn workspace_root() -> PathBuf {
    let xtask_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    xtask_dir.parent().unwrap_or(xtask_dir).to_path_buf()
}

pub fn run(check: bool) -> anyhow::Result<()> {
    let mut stale = Vec::new();
    for (output, generated) in [(OUTPUT, generate()?), (EXTS_OUTPUT, generate_exts()?)] {
        let path = workspace_root().join(output);
        let current = std::fs::read_to_string(&path).ok();
        let up_to_date = current.as_deref().map(normalize).as_deref() == Some(generated.as_str());
        if up_to_date {
            println!("{output} is up to date");
        } else if check {
            stale.push(output);
        } else {
            if let Some(dir) = path.parent() {
                std::fs::create_dir_all(dir)
                    .with_context(|| format!("could not create {}", dir.display()))?;
            }
            std::fs::write(&path, &generated)
                .with_context(|| format!("could not write {}", path.display()))?;
            println!("wrote {output}");
        }
    }
    if !stale.is_empty() {
        bail!(
            "{} out of date; run `cargo xtask codegen`",
            stale.join(" and ")
        );
    }
    Ok(())
}

/// The full contents of `gen_exts.rs`: every extension `formats.list` offers Explorer's menu
/// on (`menu`), lowercase and sorted, and the tar shorthands among the codecs'.
pub fn generate_exts() -> anyhow::Result<String> {
    let engine = Engine::new(registry());
    let out = engine
        .invoke(
            "formats.list",
            serde_json::json!({}),
            Arc::new(NonInteractive),
            discard_events(),
        )?
        .join()?;
    let list: FormatsListOutput = serde_json::from_value(out)?;
    let sorted = |exts: Vec<String>| {
        let mut exts: Vec<String> = exts.into_iter().map(|e| e.to_ascii_lowercase()).collect();
        exts.sort();
        exts.dedup();
        exts
    };
    let formats = sorted(
        list.formats
            .into_iter()
            .filter(|f| f.menu)
            .flat_map(|f| f.extensions)
            .collect(),
    );
    let codecs = sorted(list.codecs.into_iter().flat_map(|c| c.extensions).collect());
    let shorthands = sorted(
        beezip_core::codec::TAR_SHORTHANDS
            .iter()
            .map(|s| (*s).to_owned())
            .collect(),
    );
    if let Some(s) = shorthands.iter().find(|s| !codecs.contains(s)) {
        bail!("the tar shorthand {s} isn't a codec's extension");
    }
    let array = |name: &str, doc: &str, exts: &[String]| {
        let items: String = exts.iter().map(|e| format!("    \"{e}\",\n")).collect();
        format!("/// {doc}\npub const {name}: &[&str] = &[\n{items}];\n")
    };
    let text = [
        "// @generated by `cargo xtask codegen` from `formats.list`. Do not edit.\n\
         // CI fails if this file is out of date; regenerate it after changing a format or codec.\n"
            .to_owned(),
        array("FORMATS", "The archive formats' extensions.", &formats),
        array(
            "CODECS",
            "The codecs' extensions: single compressed files, and tar shorthands.",
            &codecs,
        ),
        array(
            "TAR_SHORTHANDS",
            "The codec extensions that stand for `.tar` and the codec's: `.tgz` is `.tar.gz`.",
            &shorthands,
        ),
    ]
    .join("\n");
    Ok(normalize(&text))
}

/// The full contents of `commands.ts`. Deterministic: types sorted by name, LF line endings.
pub fn generate() -> anyhow::Result<String> {
    // The wire format is JSON numbers, so u64 is `number`, not ts-rs's default `bigint`.
    let cfg = Config::new().with_large_int("number");
    let registry = registry();

    let mut decls = TsDecls::new();
    for entry in registry.entries() {
        entry
            .ts_decls(&cfg, &mut decls)
            .map_err(anyhow::Error::msg)
            .with_context(|| format!("collecting the types of `{}`", entry.name))?;
    }
    collect_ts::<JobEvent>(&cfg, &mut decls).map_err(anyhow::Error::msg)?;
    collect_ts::<CmdError>(&cfg, &mut decls).map_err(anyhow::Error::msg)?;
    collect_ts::<CommandInfo>(&cfg, &mut decls).map_err(anyhow::Error::msg)?;
    collect_ts::<JobInfo>(&cfg, &mut decls).map_err(anyhow::Error::msg)?;
    collect_ts::<PromptReply>(&cfg, &mut decls).map_err(anyhow::Error::msg)?;

    let mut out = String::from(HEADER);
    out.push_str("\nexport type JobId = number;\n");
    for decl in decls.values() {
        out.push('\n');
        out.push_str(decl.trim_end());
        out.push('\n');
    }

    out.push_str("\n/** Every command's input and output types, by command name. */\n");
    out.push_str("export type CommandMap = {\n");
    for entry in registry.entries() {
        let (input, output) = entry.ts_names(&cfg);
        out.push_str(&jsdoc(&entry.description, "  "));
        out.push_str(&format!(
            "  \"{}\": {{ input: {input}; output: {output} }};\n",
            entry.name
        ));
    }
    out.push_str("};\n\nexport type CommandName = keyof CommandMap;\n");
    Ok(normalize(&escape_doc_lines(&out)))
}

/// ts-rs copies doc comments verbatim, so a doc mentioning `docs/**/*.md` would close its
/// JSDoc block early. Inside a block's content lines (` * …`), `*/` becomes `*\/`.
fn escape_doc_lines(text: &str) -> String {
    text.lines()
        .map(|line| {
            if line.trim_start().starts_with("* ") {
                line.replace("*/", "*\\/")
            } else {
                line.to_owned()
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

fn jsdoc(text: &str, indent: &str) -> String {
    let text = text.replace("*/", "*\\/");
    let lines: Vec<&str> = text.trim().lines().collect();
    match lines.as_slice() {
        [] => String::new(),
        [line] => format!("{indent}/** {line} */\n"),
        lines => {
            let mut doc = format!("{indent}/**\n");
            for line in lines {
                doc.push_str(format!("{indent} * {line}").trim_end());
                doc.push('\n');
            }
            doc.push_str(&format!("{indent} */\n"));
            doc
        }
    }
}

/// LF endings, no trailing whitespace (ts-rs leaves some after `{`), one final newline. An
/// editor that trims on save then can't make the file look stale.
fn normalize(text: &str) -> String {
    let mut out: String = text
        .lines()
        .map(|line| format!("{}\n", line.trim_end()))
        .collect();
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}
